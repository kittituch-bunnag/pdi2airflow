def generate_dag_source(graph: WorkflowGraph) -> str:
    """Render a complete .py DAG file from the IR graph."""
    ok, issues = graph.is_resolvable()
    if not ok:
        raise ValueError(
            "Cannot generate DAG: graph has unresolved references:\n  - "
            + "\n  - ".join(issues)
        )

    today = datetime.now()
    callables_src, callables_index = _build_callables(graph)

    return DAG_TEMPLATE.format(
        description=graph.description or graph.dag_id,
        source_kjb=graph.source_kjb or "<unknown>",
        generated_at=today.isoformat(timespec="seconds"),
        connection_block=_build_connection_block(graph.connections),
        callables_block=callables_src,
        dag_id=graph.dag_id,
        description_repr=repr(graph.description or graph.dag_id),
        start_year=today.year,
        start_month=today.month,
        start_day=today.day,
        tags_repr=repr(_build_tags(graph)),
        operator_block=textwrap.indent(_build_operator_block(graph, callables_index), "    "),
        wiring_block=textwrap.indent(_build_wiring_block(graph), "    "),
    )


def _build_tags(graph: WorkflowGraph) -> list[str]:
    tags = ["pdi-migrated"]
    desc = graph.description or ""
    if desc.startswith("[") and "]" in desc:
        repo_name = desc[1:desc.index("]")]
        if repo_name and repo_name not in tags:
            tags.append(repo_name)
    return tags


