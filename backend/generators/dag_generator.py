def _build_connection_block(conns: list[ConnectionRef]) -> str:
    if not conns:
        return "# (no PDI connections referenced)"
    _HINT = {
        "exact":      "",
        "host_match": "  # <- verify: matched by hostname keyword",
        "type_match": "  # <- HIGH RISK: matched by db type only — confirm this is the right connection",
        "none":       "  # <- UNRESOLVED: no mapping found — this should have blocked generation",
    }
    lines = []
    for c in conns:
        hint = _HINT.get(c.confidence, "")
        lines.append(
            f"# PDI '{c.pdi_name}' ({c.db_type}) -> Airflow '{c.suggested_airflow_conn}' "
            f"[confidence={c.confidence}]"
        )
        sanitized = ''.join(ch if ch.isalnum() or ch == '_' else '_' for ch in c.pdi_name.upper()).strip('_') or 'UNNAMED'
        var = f"CONN_{sanitized}"
        lines.append(f'{var} = "{c.suggested_airflow_conn}"{hint}')
    return "\n".join(lines)


def _safe_sql_literal(sql: str) -> str:
    """Render a SQL string as a safe Python literal (handles backslashes and triple quotes)."""
    if sql is None:
        return '""'
    cleaned = sql.replace('\\', '\\\\').replace('"""', '\\"\\"\\"')
    return f'"""{cleaned}"""'


def _build_callables(graph: WorkflowGraph) -> tuple[str, dict[str, str]]:
    """Returns (joined source code, {node_id: function_name})."""
    parts: list[str] = []
    index: dict[str, str] = {}
    for node in graph.nodes:
        if node.kind == NodeKind.TRANSFORMATION:
            fname, src = generate_transformation_callable(node, graph.connections)
            parts.append(src)
            index[node.id] = fname
        elif node.kind == NodeKind.SQL:
            fname = f"run_sql_{node.id}"
            conn_pdi = node.config.get("connection", "")
            airflow_conn = _airflow_id_for(conn_pdi, graph.connections) or f"TODO_{conn_pdi}"
            db_type = _db_type_for(conn_pdi, graph.connections)
            sql_lit = _safe_sql_literal(node.config.get("sql") or "")
            engine_fn = "_mssql_engine" if db_type == "MSSQL" else "_pg_engine"
            parts.append(textwrap.dedent(f"""
                def {fname}(**context):
                    \"\"\"Translated from PDI SQL job entry: {node.label}\"\"\"
                    _engine = {engine_fn}("{airflow_conn}")
                    _exec_sql(_engine, {sql_lit})
            """).strip())
            index[node.id] = fname
        elif node.kind == NodeKind.EVAL:
            fname = f"branch_{node.id}"
            script = (node.config.get("script") or "").strip()
            parts.append(textwrap.dedent(f"""
                def {fname}(**context):
                    \"\"\"Translated from PDI EVAL job entry: {node.label}
                    Original PDI script:
                    {script!r}
                    TODO: implement branching logic. Return downstream task_id(s).
                    \"\"\"
                    return []  # TODO: list of task_ids to run
            """).strip())
            index[node.id] = fname
    return ("\n\n\n".join(parts) if parts else "# (no callables needed)"), index


def _build_operator_block(graph: WorkflowGraph, callables_index: dict[str, str]) -> str:
    """Emit one operator instantiation per IR node."""
    lines: list[str] = []
    for node in graph.nodes:
        if node.kind == NodeKind.START:
            lines.append(f'{node.id} = DummyOperator(task_id="{node.id}")')
        elif node.kind == NodeKind.END:
            lines.append(textwrap.dedent(f'''\
                {node.id} = DummyOperator(
                    task_id="{node.id}",
                    trigger_rule="none_failed",
                )''').strip())
        elif node.kind == NodeKind.DUMMY:
            lines.append(f'{node.id} = DummyOperator(task_id="{node.id}")')
        elif node.kind == NodeKind.TRANSFORMATION:
            fname = callables_index.get(node.id, "lambda **k: None")
            lines.append(textwrap.dedent(f'''\
                {node.id} = PythonOperator(
                    task_id="{node.id}",
                    python_callable={fname},
                )''').strip())
        elif node.kind == NodeKind.SQL:
            fname = callables_index.get(node.id, "lambda **k: None")
            lines.append(textwrap.dedent(f'''\
                {node.id} = PythonOperator(
                    task_id="{node.id}",
                    python_callable={fname},
                )''').strip())
        elif node.kind == NodeKind.SHELL:
            script = (node.config.get("script") or "").replace('"', '\\"')
            lines.append(textwrap.dedent(f'''\
                {node.id} = BashOperator(
                    task_id="{node.id}",
                    bash_command="""{script}""",
                )''').strip())
        elif node.kind == NodeKind.EVAL:
            fname = callables_index.get(node.id, "lambda **k: []")
            lines.append(textwrap.dedent(f'''\
                {node.id} = BranchPythonOperator(
                    task_id="{node.id}",
                    python_callable={fname},
                )''').strip())
        elif node.kind == NodeKind.WAITFOR:
            timeout = node.config.get("maximum_timeout", "0")
            lines.append(textwrap.dedent(f'''\
                # PDI WAITFOR: {node.label} (timeout={timeout}s)
                # TODO: replace with TimeDeltaSensor or appropriate sensor
                {node.id} = DummyOperator(task_id="{node.id}")''').strip())
        elif node.kind == NodeKind.SUBJOB:
            lines.append(textwrap.dedent(f'''\
                # PDI SUBJOB: {node.label}
                # TODO: replace with TriggerDagRunOperator targeting the migrated sub-DAG
                {node.id} = DummyOperator(task_id="{node.id}")''').strip())
        else:
            lines.append(textwrap.dedent(f'''\
                # UNKNOWN PDI entry type — review original .kjb
                {node.id} = DummyOperator(task_id="{node.id}")''').strip())
    return "\n".join(lines)


def _build_wiring_block(graph: WorkflowGraph) -> str:
    """Emit `a >> b` lines from edges. Group by source for readability."""
    if not graph.edges:
        return "# (no edges)"
    by_src: dict[str, list[str]] = {}
    for e in graph.edges:
        by_src.setdefault(e.source, []).append(e.target)
    lines: list[str] = []
    for src, tgts in by_src.items():
        if len(tgts) == 1:
            lines.append(f"{src} >> {tgts[0]}")
        else:
            tgt_list = ", ".join(tgts)
            lines.append(f"{src} >> [{tgt_list}]")
    return "\n".join(lines)


def _airflow_id_for(pdi_name: str, conns: list[ConnectionRef]) -> str | None:
    for c in conns:
        if c.pdi_name == pdi_name:
            return c.suggested_airflow_conn
    return None


def _db_type_for(pdi_name: str, conns: list[ConnectionRef]) -> str:
    for c in conns:
        if c.pdi_name == pdi_name:
            return (c.db_type or "").upper()
    return "UNKNOWN"


