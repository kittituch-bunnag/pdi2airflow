_CONF_BADGE = {
    "exact":      "✅ exact",
    "host_match": "⚠️ host\\_match",
    "type_match": "🔴 type\\_match",
    "none":       "❌ none",
}
_CONF_ACTION = {
    "exact":      "Confirm conn\\_id exists in Airflow.",
    "host_match": "**Verify** host, database, and credentials match.",
    "type_match": "**HIGH RISK** — matched by DB type only. Manually confirm the correct conn\\_id.",
    "none":       "**UNRESOLVED** — no mapping found.",
}


def generate_migration_report(graph: WorkflowGraph) -> str:
    """A markdown summary documenting how the DAG maps back to the PDI source."""
    lines = [
        f"# Migration Report — `{graph.dag_id}`",
        "",
        f"Source: `{graph.source_kjb or 'unknown'}`",
        f"Description: {graph.description or '_(none)_'}",
        "",
        "> [!WARNING]",
        "> **ACTION REQUIRED — verify all connections before enabling this DAG.**",
        "> ",
        "> Each `CONN_*` variable in the generated `.py` file was auto-mapped from a PDI",
        "> connection definition. You **must** confirm every conn\\_id exists in Airflow",
        "> (**Admin → Connections**) and points to the correct host, database, and credentials.",
        "> ",
        "> | Badge | Confidence | What to do |",
        "> |---|---|---|",
        "> | ✅ exact | PDI name matched an Airflow conn\\_id directly | Still confirm it exists |",
        "> | ⚠️ host\\_match | Matched by hostname / DB-type keyword | Verify host, DB, credentials |",
        "> | 🔴 type\\_match | Matched by DB type only | **Manually identify the right conn\\_id** |",
        "",
        "## Connections",
        "",
    ]
    if graph.connections:
        lines.append("| PDI Name | Type | Host | Database | Airflow conn\\_id | Confidence | Action |")
        lines.append("|---|---|---|---|---|---|---|")
        for c in graph.connections:
            badge  = _CONF_BADGE.get(c.confidence, c.confidence)
            action = _CONF_ACTION.get(c.confidence, "")
            lines.append(
                f"| `{c.pdi_name}` | {c.db_type} | {c.host or '-'} | "
                f"{c.database or '-'} | `{c.suggested_airflow_conn or '?'}` | {badge} | {action} |"
            )
    else:
        lines.append("_No connections referenced._")

    lines.extend(["", "## Variables", ""])
    if graph.variables:
        lines.append("| Variable | Used by tasks | Default |")
        lines.append("|---|---|---|")
        for v in graph.variables:
            lines.append(
                f"| `${{{v.name}}}` | {', '.join(v.used_in) or '-'} | "
                f"{v.default_value or '_(none — set as Airflow Variable)_'} |"
            )
    else:
        lines.append("_No variables referenced._")

    lines.extend(["", "## Tasks", ""])
    lines.append("| Task ID | Kind | Source | Notes |")
    lines.append("|---|---|---|---|")
    for n in graph.nodes:
        notes = ""
        if n.kind == NodeKind.TRANSFORMATION and n.steps:
            unmapped = sorted({s.pdi_type for s in n.steps if s.pdi_type not in KNOWN_STEP_TYPES})
            if unmapped:
                notes = "Unmapped step types: " + ", ".join(unmapped)
        lines.append(f"| `{n.id}` | {n.kind.value} | {n.source_file or '-'} | {notes} |")

    if graph.unmapped_step_types:
        lines.extend([
            "",
            "## Unmapped PDI Step Types",
            "",
            "These PDI step types have no translation; the generated code",
            "contains TODO stubs that must be implemented manually:",
            "",
        ])
        for t in graph.unmapped_step_types:
            lines.append(f"- `{t}`")

    return "\n".join(lines) + "\n"
