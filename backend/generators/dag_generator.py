def _pg_engine(conn_id):
    c = BaseHook.get_connection(conn_id)
    return create_engine(_SA_URL.create(
        "postgresql+psycopg2",
        username=c.login, password=c.password,
        host=c.host, port=c.port or 5432, database=c.schema,
    ))


def _mssql_engine(conn_id):
    c = BaseHook.get_connection(conn_id)
    return create_engine(_SA_URL.create(
        "mssql+pymssql",
        username=c.login, password=c.password,
        host=c.host, port=c.port or 1433, database=c.schema,
    ))


def _table_cols(engine, table):
    """Return column names for *table* (optionally schema-qualified)."""
    schema = table.split(".")[0] if "." in table else None
    tbl = table.split(".")[-1]
    from sqlalchemy import inspect as _sa_inspect
    return [col["name"] for col in _sa_inspect(engine).get_columns(tbl, schema=schema or None)]


def _exec_sql(engine, sql):
    """Execute *sql* on *engine* without returning rows."""
    with engine.begin() as conn:
        conn.execute(text(sql))


def _df_insert(df, engine, table, truncate=False):
    """Append *df* into *table*; optionally TRUNCATE first."""
    schema = table.split(".")[0] if "." in table else None
    tbl = table.split(".")[-1]
    if truncate:
        _exec_sql(engine, "TRUNCATE TABLE %s" % table)
    df.to_sql(tbl, engine, schema=schema, if_exists="append", index=False)


def _upsert_pg(df, engine, table, pkey):
    """PostgreSQL INSERT ... ON CONFLICT (pkey) DO UPDATE SET ..."""
    from psycopg2.extras import execute_values
    schema = table.split(".")[0] if "." in table else None
    tbl = table.split(".")[-1]
    cols = list(df.columns)
    qualified = ('"%s"."%s"' % (schema, tbl)) if schema else ('"%s"' % tbl)
    upd_cols = [c for c in cols if c not in pkey]
    conflict_cols = ", ".join('"%s"' % c for c in pkey)
    ins_cols = ", ".join('"%s"' % c for c in cols)
    if upd_cols:
        set_clause = ", ".join('"%s" = EXCLUDED."%s"' % (c, c) for c in upd_cols)
        on_conflict = "DO UPDATE SET %s" % set_clause
    else:
        on_conflict = "DO NOTHING"
    upsert_sql = (
        "INSERT INTO %s (%s) VALUES %%s ON CONFLICT (%s) %s"
        % (qualified, ins_cols, conflict_cols, on_conflict)
    )
    raw = engine.raw_connection()
    try:
        execute_values(raw.cursor(), upsert_sql, [tuple(r) for r in df.itertuples(index=False)])
        raw.commit()
    except Exception:
        raw.rollback()
        raise
    finally:
        raw.close()


